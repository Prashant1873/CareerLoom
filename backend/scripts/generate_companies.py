def main():
    target_file = Path(__file__).resolve().parent.parent / "app" / "data" / "companies.json"
    
    # Deduplicate by slug and name
    seen_slugs = set()
    deduped = []
    for c in COMPANIES:
        slug_key = f"{c['ats_type']}:{c['slug'].lower()}"
        if slug_key not in seen_slugs:
            seen_slugs.add(slug_key)
            deduped.append(c)

    print(f"Total unique companies compiled: {len(deduped)}")
    with open(target_file, "w", encoding="utf-8") as f:
        json.dump(deduped, f, indent=2)
    print(f"Successfully wrote {len(deduped)} companies to {target_file}")

if __name__ == "__main__":
    main()
